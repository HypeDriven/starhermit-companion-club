// Writes tests/native/club-day.play: the first club day (Content.JOURNEY[0],
// seeded) played to its results by the hint, as a player pressing H and then
// the key the hint names (the hint selects its friend; S serves, T tidies,
// the arrows move), simulated here with the shipped rules (js/rules.js) so
// the script stays in step with them. Then Play again starts a fresh day.
//   node tools/gen-play.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const R = require('../js/rules.js');
const C = require('../js/content.js');

const KEY = { up: 'ArrowUp', down: 'ArrowDown', left: 'ArrowLeft', right: 'ArrowRight' };
let s = R.createGame(C.JOURNEY[0]);
const lines = [
  '# The first club day played to its results by the hint (generated by',
  '# tools/gen-play.mjs from js/rules.js): H, then the key the hint names.',
  'until 300 =Play',
  'frames 10',
  'click =Play',
  'until 60 Clubhouse floor',
  'frames 10',
  'expect Served 0/3',
];
let n = 0;
while (!s.terminal && n < 200) {
  const h = R.hint(s);
  if (!h) throw new Error('no hint');
  const a = h.action;
  const key = a.type === 'serve' ? 'KeyS' : a.type === 'tidy' ? 'KeyT' : KEY[a.dir];
  lines.push('key KeyH 1', 'frames 3', `key ${key} 1`, 'frames 3');
  // the client's tidy picks the first messy station within reach, as the hint's does
  const out = R.applyCommand(s, a);
  if (!out.ok) throw new Error('hint refused: ' + out.reason);
  s = out.state;
  n++;
  if (n === 2) lines.push('save club-day-moving');
}
if (!s.terminal.won) throw new Error('the hint did not win the day');
lines.push(
  `# ${n} turns, ${s.score.total} points`,
  'until 60 Club day complete!',
  'frames 30',
  `expect =${s.score.total}`,
  'expect Every wish on the club list was fulfilled in time.',
  'save club-day-results',
  'frames 10',
  'click =Play again',
  'until 60 Served 0/3',
  'frames 10',
  'save club-day-again',
);
writeFileSync(join(root, 'tests/native/club-day.play'), lines.join('\n') + '\n');
console.log(`club-day.play: ${n} turns, ${s.score.total} points`);
